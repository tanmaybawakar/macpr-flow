import AppKit
import ApplicationServices
import Carbon

enum InsertResult {
    /// Where the text went, when the app exposes it, so later edits can teach the dictionary.
    case pasted(CaretContext?)
    case copied(String)
}

struct CaretContext {
    let element: AXUIElement
    /// UTF-16 offset of the caret (or the start of the selection) before the paste.
    let location: Int
}

/// Puts text where the cursor is, in any app: native, Electron, Chrome, terminals.
///
/// Paste is the one path that works everywhere, so it is the only path. Accessibility is used solely
/// to peek at the character before the caret for spacing, with a short timeout so a hung app can't stall us.
@MainActor
enum Inserter {
    private static var pendingRestore: (snapshot: [[NSPasteboard.PasteboardType: Data]], change: Int)?
    private static var restoreTask: Task<Void, Never>?

    static func insert(_ text: String, smartSpacing: Bool) -> InsertResult {
        if IsSecureEventInputEnabled() {
            copy(text)
            return .copied("A password field is active, so your text was copied instead. Press ⌘V to paste it.")
        }
        guard NSWorkspace.shared.frontmostApplication != nil else {
            copy(text)
            return .copied("No app is ready for text, so it was copied. Press ⌘V to paste it.")
        }
        let context = caretContext()
        var output = text
        var start = context?.location
        if smartSpacing, let context {
            output = Spacing.adjust(text, after: characterBefore(context))
            if output.count > text.count { start = context.location + 1 }
        }
        paste(output)
        return .pasted(start.flatMap { location in context.map { CaretContext(element: $0.element, location: location) } })
    }

    static func copy(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        pendingRestore = nil; restoreTask?.cancel()
    }

    // MARK: Paste, then put the clipboard back

    private static func paste(_ text: String) {
        let board = NSPasteboard.general
        // Back-to-back dictations keep the user's original clipboard, not our previous paste.
        let snapshot = pendingRestore?.snapshot ?? capture(board)
        board.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Clipboard managers skip transient items, so dictations don't flood their history.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        board.writeObjects([item])
        let change = board.changeCount
        pendingRestore = (snapshot, change)
        postCommandV()
        restoreTask?.cancel()
        restoreTask = Task { @MainActor in
            do { try await Task.sleep(for: .milliseconds(1200)) } catch { return }
            if let pending = pendingRestore, board.changeCount == pending.change { restore(pending.snapshot, to: board) }
            pendingRestore = nil
        }
    }

    private static func capture(_ board: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (board.pasteboardItems ?? []).map { item in
            Dictionary(uniqueKeysWithValues: item.types.compactMap { type in item.data(forType: type).map { (type, $0) } })
        }
    }

    private static func restore(_ snapshot: [[NSPasteboard.PasteboardType: Data]], to board: NSPasteboard) {
        board.clearContents()
        let items = snapshot.map { values in
            let item = NSPasteboardItem()
            for (type, data) in values { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { board.writeObjects(items) }
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let key = pasteKeyCode()
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false) else { return }
        down.flags = .maskCommand; up.flags = .maskCommand
        down.post(tap: .cghidEventTap); up.post(tap: .cghidEventTap)
    }

    private static var cachedLayout: (id: String, code: CGKeyCode)?

    /// The key that types ⌘V on the current layout (Dvorak, AZERTY and "Dvorak – QWERTY ⌘" differ).
    static func pasteKeyCode() -> CGKeyCode {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let idPointer = TISGetInputSourceProperty(source, kTISPropertyInputSourceID),
              let dataPointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return 9 }
        let id = Unmanaged<CFString>.fromOpaque(idPointer).takeUnretainedValue() as String
        if let cachedLayout, cachedLayout.id == id { return cachedLayout.code }
        let data = Unmanaged<CFData>.fromOpaque(dataPointer).takeUnretainedValue() as Data
        let code: CGKeyCode = data.withUnsafeBytes { raw in
            guard let layout = raw.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return 9 }
            let commandState = UInt32((cmdKey >> 8) & 0xFF)
            for candidate in 0..<128 {
                var dead: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(candidate), UInt16(kUCKeyActionDown), commandState,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &dead, 4, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(118) { return CGKeyCode(candidate) }
            }
            return 9
        }
        cachedLayout = (id, code)
        return code
    }

    // MARK: Smart spacing

    static func caretContext() -> CaretContext? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.15)
        guard let focused = value(system, kAXFocusedUIElementAttribute), CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.15)
        guard let rangeValue = value(element, kAXSelectedTextRangeAttribute), CFGetTypeID(rangeValue) == AXValueGetTypeID() else { return nil }
        var range = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &range) else { return nil }
        return CaretContext(element: element, location: range.location)
    }

    /// The character just before the caret, "\n" at the start of a field, or nil when the app doesn't say.
    static func characterBefore(_ context: CaretContext) -> Character? {
        if context.location <= 0 { return "\n" }
        var previous = CFRange(location: context.location - 1, length: 1)
        if let parameter = AXValueCreate(.cfRange, &previous) {
            var out: CFTypeRef?
            if AXUIElementCopyParameterizedAttributeValue(context.element, kAXStringForRangeParameterizedAttribute as CFString, parameter, &out) == .success,
               let string = out as? String, let last = string.last {
                return last
            }
        }
        return text(of: context.element).flatMap { whole in
            let utf16 = whole.utf16
            guard let index = utf16.index(utf16.startIndex, offsetBy: context.location, limitedBy: utf16.endIndex) else { return nil }
            return whole[..<index].last
        }
    }

    static func text(of element: AXUIElement) -> String? {
        value(element, kAXValueAttribute) as? String
    }

    private static func value(_ element: AXUIElement, _ name: String) -> CFTypeRef? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success else { return nil }
        return value
    }
}
